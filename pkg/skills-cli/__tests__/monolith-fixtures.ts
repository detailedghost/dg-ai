export function writeTree(root: string, files: Record<string, string>): void {
	for (const [name, text] of Object.entries(files)) {
		const path = join(root, name);
		mkdirSync(dirname(path), { recursive: true });
		writeFileSync(path, text);
	}
}

export function monolithEnv(
	context: SpecContext,
	extra: Record<string, string | undefined> = {},
): Record<string, string> {
	return mergeEnv({
		...baseEnv(context),
		DG_SKILLS_DIR: SOURCE_SKILLS,
		SCRIPTS_ROOT: undefined,
		MONOLITH_NONINTERACTIVE: undefined,
		...extra,
	});
}

export interface MonolithOptions {
	cwd: string;
	env?: Record<string, string | undefined>;
}

export function runMonolith(
	context: SpecContext,
	args: string[],
	options: Partial<MonolithOptions> = {},
): Promise<SpecRun> {
	return collectRun(
		Bun.spawn(
			[
				process.execPath,
				"--preload",
				SPEC_FIXED_DATE_PRELOAD,
				SPEC_ENTRY,
				"monolith",
				...args,
			],
			{
				cwd: options.cwd ?? context.root,
				env: monolithEnv(context, options.env),
				stdin: "ignore",
				stdout: "pipe",
				stderr: "pipe",
			},
		),
	);
}

export interface GeneratedScan {
	mode: string;
	monolithPath: string;
	stagingPath: string;
	existingTerms: string;
	existingFileContent: string;
	template: string;
	agentTypes: { domain: string; naming: string; concept: string };
	SCAN_ROOT: string;
}

const GENERATED_CONSTS = [
	"mode",
	"monolithPath",
	"stagingPath",
	"existingTerms",
	"existingFileContent",
	"template",
	"agentTypes",
	"SCAN_ROOT",
] as const;

export function parseGeneratedScan(script: string): GeneratedScan {
	const found: Record<string, unknown> = {};
	for (const name of GENERATED_CONSTS) {
		const line = script
			.split("\n")
			.find((candidate) => candidate.startsWith(`const ${name} = `));
		if (line === undefined) throw new Error(`generated script lacks ${name}`);
		found[name] = JSON.parse(
			line.slice(`const ${name} = `.length).replace(/;$/, ""),
		);
	}
	return found as unknown as GeneratedScan;
}
