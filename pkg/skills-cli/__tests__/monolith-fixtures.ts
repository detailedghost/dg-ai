export type TermSection = (typeof TERM_SECTIONS)[number];

export interface TermRow {
	section: TermSection;
	term: string;
	definition?: string;
	src?: string;
}

export const SOFT_CAP_BYTES = 6144;
export const SOFT_CAP_ROWS = 40;

const TABLE_HEAD = ["| Term | Definition |", "|------|------------|"];

export function termRowLine(row: TermRow): string {
	const definition = row.definition ?? `${row.term} definition.`;
	const src = row.src ? ` _src:_ ${row.src}` : "";
	return `| **${row.term}** | ${definition}${src} |`;
}

export function vocabulary(
	rows: TermRow[],
	extra: { title?: string; trailing?: string } = {},
): string {
	const parts = [
		extra.title ?? "# Project Vocabulary",
		"<!-- Generated by /monolith. -->",
	];
	for (const section of TERM_SECTIONS) {
		parts.push("", `## ${section}`, "", ...TABLE_HEAD);
		for (const row of rows)
			if (row.section === section) parts.push(termRowLine(row));
	}
	if (extra.trailing) parts.push("", extra.trailing);
	return `${parts.join("\n")}\n`;
}

export function domainRows(
	domain: string,
	count: number,
	section: TermSection = "Domain Terms",
): TermRow[] {
	return Array.from({ length: count }, (_, index) => ({
		section,
		term: `${domain}Term${index}`,
		src: `pkg/${domain}/File${index}.ts`,
	}));
}

