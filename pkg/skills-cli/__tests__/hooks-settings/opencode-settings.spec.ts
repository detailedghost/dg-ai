import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import {
	chmodSync,
	lstatSync,
	mkdirSync,
	readFileSync,
	renameSync,
	statSync,
	symlinkSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { ownedCommand } from "../../src/hooks/settings/marker";
import { settingsWorld } from "./settings-fixtures";

let world: ReturnType<typeof settingsWorld>;
beforeEach(() => {
	world = settingsWorld();
	world.seed(world.paths.opencodeJson, {
		theme: "tokyo",
		plugin: ["other-plugin"],
	});
});
afterEach(() => world.cleanup());

const HEADER = "generated by dg-skills hooks; do not edit";

describe("opencode settings writer", () => {
	test("enable writes dg-hooks.js with the enabled ids and never adds a plugin entry", async () => {
		await world.cli(["enable", "spelling", "--runtime", "opencode"]);
		await world.cli(["enable", "pr-prose", "--runtime", "opencode"]);
		const plugin = world.text(world.paths.opencodePlugin);
		expect(plugin.split("\n")[0]).toContain(HEADER);
		expect(plugin).toContain(ownedCommand(world.launcher, "spelling"));
		expect(plugin).toContain(ownedCommand(world.launcher, "pr-prose"));
		expect(plugin).toContain("tool.execute.before");
		expect(plugin).toContain("tool.execute.after");
		expect(plugin).not.toContain("shell: true");
		expect(world.readJson(world.paths.opencodeJson)).toEqual({
			theme: "tokyo",
			plugin: ["other-plugin"],
		});
	});

	test("enable removes a legacy bare dg-hooks plugin entry", async () => {
		world.seed(world.paths.opencodeJson, {
			plugin: ["other-plugin", "dg-hooks"],
		});
		await world.cli(["enable", "spelling", "--runtime", "opencode"]);
		expect(
			world.readJson<{ plugin: string[] }>(world.paths.opencodeJson).plugin,
		).toEqual(["other-plugin"]);
	});

	test("XDG_CONFIG_HOME relocates the opencode directory", async () => {
		const xdg = join(world.home, "xdg");
		const result = await world.cli(
			["enable", "spelling", "--runtime", "opencode"],
			{ env: { XDG_CONFIG_HOME: xdg } },
		);
		expect(result.code).toBe(0);
		expect(world.has(join(xdg, "opencode", "plugins", "dg-hooks.js"))).toBe(
			true,
		);
		expect(world.has(world.paths.opencodePlugin)).toBe(false);
	});

	test("invalid opencode.json gives exit 1, no plugin file and untouched bytes", async () => {
		const bad = "{ // comment\n}";
		world.seed(world.paths.opencodeJson, bad);
		const result = await world.cli([
			"enable",
			"spelling",
			"--runtime",
			"opencode",
		]);
		expect(result.code).toBe(1);
		expect(world.has(world.paths.opencodePlugin)).toBe(false);
		expect(world.text(world.paths.opencodeJson)).toBe(bad);
	});

	test("disable --all removes the legacy entry even when dg-hooks.js is gone", async () => {
		world.seed(world.paths.opencodeJson, { plugin: ["dg-hooks", "keep"] });
		const result = await world.cli([
			"disable",
			"--all",
			"--runtime",
			"opencode",
		]);
		expect(result.code).toBe(0);
		expect(
			world.readJson<{ plugin: string[] }>(world.paths.opencodeJson).plugin,
		).toEqual(["keep"]);
	});

	test("a dg-hooks.js without the header is never overwritten or removed", async () => {
		const mine = "export default () => ({});\n";
		world.seed(world.paths.opencodePlugin, mine);
		for (const argv of [
			["enable", "spelling", "--runtime", "opencode"],
			["disable", "--all", "--runtime", "opencode"],
		]) {
			const result = await world.cli(argv);
			expect(result.code).toBe(1);
			expect(world.text(world.paths.opencodePlugin)).toBe(mine);
		}
	});

	test("disable rebuilds kept entries from the manifest, not from the file", async () => {
		await world.cli(["enable", "spelling", "format", "--runtime", "opencode"]);
		const tampered = world
			.text(world.paths.opencodePlugin)
			.replaceAll(ownedCommand(world.launcher, "format"), "evil --run");
		world.seed(world.paths.opencodePlugin, tampered);
		await world.cli(["disable", "spelling", "--runtime", "opencode"]);
		const plugin = world.text(world.paths.opencodePlugin);
		expect(plugin).not.toContain("evil");
		expect(plugin).toContain(ownedCommand(world.launcher, "format"));
	});

	test("the plugin file is not world-writable", async () => {
		await world.cli(["enable", "spelling", "--runtime", "opencode"]);
		expect(statSync(world.paths.opencodePlugin).mode & 0o022).toBe(0);
	});

	test("SessionStart hooks are skipped for opencode", async () => {
		await world.cli(["enable", "spelling", "--runtime", "opencode"]);
		await world.cli(["enable", "daily-prune", "--runtime", "opencode"]);
		expect(world.text(world.paths.opencodePlugin)).not.toContain(
			ownedCommand(world.launcher, "daily-prune"),
		);
	});

	test("disable of the last id removes dg-hooks.js and keeps other plugins", async () => {
		await world.cli(["enable", "spelling", "--runtime", "opencode"]);
		await world.cli(["disable", "spelling", "--runtime", "opencode"]);
		expect(world.has(world.paths.opencodePlugin)).toBe(false);
		const json = world.readJson<{ plugin: string[] }>(world.paths.opencodeJson);
		expect(json.plugin).toEqual(["other-plugin"]);
	});

	test("disable of one id keeps the others in the plugin", async () => {
		await world.cli(["enable", "spelling", "--runtime", "opencode"]);
		await world.cli(["enable", "format", "--runtime", "opencode"]);
		await world.cli(["disable", "spelling", "--runtime", "opencode"]);
		const plugin = world.text(world.paths.opencodePlugin);
		expect(plugin).not.toContain(ownedCommand(world.launcher, "spelling"));
		expect(plugin).toContain(ownedCommand(world.launcher, "format"));
	});
});

describe("opencode plugin file handling", () => {
	test.skipIf(process.platform === "win32")(
		"enabling another hook keeps a symlinked dg-hooks.js and its mode",
		async () => {
			expect(
				(await world.cli(["enable", "spelling", "--runtime", "opencode"])).code,
			).toBe(0);
			const target = join(world.dgHome, "dotfiles", "dg-hooks.js");
			mkdirSync(dirname(target), { recursive: true });
			renameSync(world.paths.opencodePlugin, target);
			chmodSync(target, 0o600);
			symlinkSync(target, world.paths.opencodePlugin);
			expect(
				(await world.cli(["enable", "format", "--runtime", "opencode"])).code,
			).toBe(0);
			expect(lstatSync(world.paths.opencodePlugin).isSymbolicLink()).toBe(true);
			expect(statSync(target).mode & 0o777).toBe(0o600);
			expect(readFileSync(target, "utf8")).toContain("format");
		},
	);
});
