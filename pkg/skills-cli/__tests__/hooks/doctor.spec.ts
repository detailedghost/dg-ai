import { describe, expect, test } from "bun:test";
import { chmodSync } from "node:fs";
import { join } from "node:path";
import { CLI_PATH } from "../../src/doctor/probes";
import type { DoctorContext } from "../../src/doctor/types";
import { HOOKS_ALLOW_RULES, hooksChecks } from "../../src/hooks/doctor";
import { ownedCommand } from "../../src/hooks/settings/marker";
import { settingsWorld, USER_HOOK } from "../hooks-settings/settings-fixtures";

const RUNTIME_IDS = ["settings-claude", "settings-codex", "settings-opencode"];

function setup(env: NodeJS.ProcessEnv = { PATH: "" }) {
	const world = settingsWorld();
	const ctx = {
		home: world.home,
		env,
		paths: {},
		installedVersion: "0.0.0",
		memo: <T>(_key: string, make: () => T) => make(),
	} as unknown as DoctorContext;
	const run = async (id: string) => {
		const check = hooksChecks.find((c) => c.id === id);
		if (!check) throw new Error(`no hooks check ${id}`);
		return check.run(ctx);
	};
	const hooksFile = (command: string) => ({
		hooks: {
			PostToolUse: [{ matcher: "Edit", hooks: [{ type: "command", command }] }],
		},
	});
	const claudeWith = (command: string) =>
		world.seed(world.paths.claude, hooksFile(command));
	const codexWith = (command: string) =>
		world.seed(world.paths.codex, hooksFile(command));
	const allowWith = (allow: string[]) =>
		world.seed(world.paths.claude, { permissions: { allow } });
	return { world, run, claudeWith, codexWith, allowWith };
}

function pluginSource(list: string): string {
	return `// generated by dg-skills hooks; do not edit\nconst HOOKS = ${list};\nexport default async () => ({});\n`;
}

function pluginWith(argv0: string): string {
	return pluginSource(
		JSON.stringify([
			{
				id: "format",
				event: "PostToolUse",
				matcher: "Edit",
				command: "x",
				argv: [argv0, "hooks", "run", "format"],
			},
		]),
	);
}

const missing = (world: ReturnType<typeof settingsWorld>) =>
	join(world.dgHome, "gone", "dg-skills");

describe("hooksChecks order", () => {
	test("lists skill files, the three settings checks, stale entries and the allow rule", () => {
		expect(hooksChecks.map((c) => c.id)).toEqual([
			"skill-files",
			...RUNTIME_IDS,
			"stale-entries",
			"allow-rule",
		]);
	});
});

describe("settings checks", () => {
	test("return ok for every settings and stale check when no settings files exist", async () => {
		const { run } = setup();
		for (const id of [...RUNTIME_IDS, "stale-entries"])
			expect((await run(id)).status).toBe("ok");
	});

	test("settings-claude warns when settings.json is invalid JSON", async () => {
		const { world, run } = setup();
		world.seed(world.paths.claude, "{ not json");
		const result = await run("settings-claude");
		expect(result.status).toBe("warn");
		expect(result.fix).toContain(world.paths.claude);
	});

	test("settings-opencode warns when dg-hooks.js lacks the generated header", async () => {
		const { world, run } = setup();
		world.seed(world.paths.opencodePlugin, "export default () => ({});\n");
		expect((await run("settings-opencode")).status).toBe("warn");
	});

	test("settings-opencode warns when the HOOKS line is not valid JSON", async () => {
		const { world, run } = setup();
		world.seed(world.paths.opencodePlugin, pluginSource("[{ not json"));
		expect((await run("settings-opencode")).status).toBe("warn");
	});
});

describe("stale-entries", () => {
	test("warns on a claude entry with a missing launcher and never suggests enable", async () => {
		const { world, run, claudeWith } = setup();
		claudeWith(ownedCommand(missing(world), "format"));
		const result = await run("stale-entries");
		expect(result.status).toBe("warn");
		expect(result.detail).toContain("claude:format");
		expect(result.fix).toContain("hooks disable format --runtime claude");
		expect(result.fix).not.toContain("hooks enable");
	});

	test("warns on a codex entry with a missing launcher", async () => {
		const { world, run, codexWith } = setup();
		codexWith(ownedCommand(missing(world), "spelling"));
		const result = await run("stale-entries");
		expect(result.status).toBe("warn");
		expect(result.detail).toContain("codex:spelling");
		expect(result.fix).toContain("hooks disable spelling --runtime codex");
	});

	test("lists every runtime when two runtimes hold stale entries", async () => {
		const { world, run, claudeWith, codexWith } = setup();
		claudeWith(ownedCommand(missing(world), "format"));
		codexWith(ownedCommand(missing(world), "spelling"));
		const result = await run("stale-entries");
		expect(result.status).toBe("warn");
		expect(result.detail).toContain("claude:format codex:spelling");
		expect(result.fix).toContain(
			"hooks disable format --runtime claude; ~/.dg/bin/dg-skills hooks disable spelling --runtime codex",
		);
	});

	test("is ok when the claude launcher path exists", async () => {
		const { world, run, claudeWith } = setup();
		const launcher = world.seed(join(world.dgHome, "bin", "dg-skills"), "x");
		claudeWith(ownedCommand(launcher, "format"));
		expect((await run("stale-entries")).status).toBe("ok");
	});

	test("is ok when a bare dg-skills launcher resolves through PATH", async () => {
		const world = settingsWorld();
		const bin = join(world.dgHome, "bin");
		chmodSync(world.seed(join(bin, "dg-skills"), "x"), 0o755);
		const { run, claudeWith } = setup({ PATH: bin });
		claudeWith("dg-skills hooks run format");
		expect((await run("stale-entries")).status).toBe("ok");
	});

	test("reads the opencode plugin list and warns on a missing argv0", async () => {
		const { world, run } = setup();
		world.seed(world.paths.opencodePlugin, pluginWith("/nowhere/dg-skills"));
		const result = await run("stale-entries");
		expect(result.status).toBe("warn");
		expect(result.detail).toContain("opencode:format");
	});

	test("reports opencode as unreadable when an entry has no argv", async () => {
		const { world, run } = setup();
		world.seed(
			world.paths.opencodePlugin,
			pluginSource(JSON.stringify([{ id: "format" }])),
		);
		const result = await run("stale-entries");
		expect(result.status).toBe("warn");
		expect(result.detail).toBe("could not read dg hook entries for: opencode");
	});

	test("shows stale entries and unreadable runtimes in one warning", async () => {
		const { world, run, claudeWith } = setup();
		claudeWith(ownedCommand(missing(world), "format"));
		world.seed(world.paths.codex, "{ not json");
		const result = await run("stale-entries");
		expect(result.status).toBe("warn");
		expect(result.detail).toBe(
			"dg hook entries point at a missing dg-skills: claude:format; could not read dg hook entries for: codex",
		);
		expect(result.fix).toContain("hooks disable format --runtime claude");
		expect(result.fix).toContain("fix the settings file");
	});

	test("treats a quoted Windows drive-letter launcher as an absolute path", async () => {
		const { run, claudeWith } = setup();
		claudeWith(ownedCommand("C:\\Users\\u\\.dg\\bin\\dg-skills.exe", "format"));
		const result = await run("stale-entries");
		expect(result.status).toBe("warn");
		expect(result.detail).toContain("claude:format");
	});

	test("ignores a user command that only mentions dg-skills", async () => {
		const { run, claudeWith } = setup();
		claudeWith("echo dg-skills hooks run format && /nowhere/dg-skills");
		expect((await run("stale-entries")).status).toBe("ok");
	});

	test("ignores user-owned hook entries", async () => {
		const { world, run } = setup();
		world.seed(world.paths.claude, {
			hooks: { PostToolUse: [{ hooks: [USER_HOOK] }] },
		});
		expect((await run("stale-entries")).status).toBe("ok");
	});
});

describe("allow-rule", () => {
	const enableCommand = `${CLI_PATH} hooks enable spelling`;
	const prefixOf = (rule: string) =>
		rule.replace(/^Bash\(/, "").replace(/:\*\)$/, "");

	test("suggests only rules that never match hooks enable", () => {
		expect(HOOKS_ALLOW_RULES).toEqual([
			`Bash(${CLI_PATH} hooks status:*)`,
			`Bash(${CLI_PATH} hooks list:*)`,
			`Bash(${CLI_PATH} hooks disable:*)`,
		]);
		for (const rule of HOOKS_ALLOW_RULES)
			expect(enableCommand.startsWith(prefixOf(rule))).toBe(false);
	});

	test("warns with the scoped rules as the fix when none are present", async () => {
		const { run } = setup();
		const result = await run("allow-rule");
		expect(result.status).toBe("warn");
		expect(result.fix).toBe(HOOKS_ALLOW_RULES.join(" "));
	});

	test("is ok when every scoped rule is present", async () => {
		const { run, allowWith } = setup();
		allowWith([...HOOKS_ALLOW_RULES]);
		expect((await run("allow-rule")).status).toBe("ok");
	});

	test("warns when a broad rule also allows hooks enable", async () => {
		const { run, allowWith } = setup();
		allowWith([`Bash(${CLI_PATH} hooks:*)`]);
		const result = await run("allow-rule");
		expect(result.status).toBe("warn");
		expect(result.detail).toContain("also allows hooks enable");
		expect(result.fix).toContain(HOOKS_ALLOW_RULES[0]);
	});

	test("warns when the dg-skills wildcard rule is present", async () => {
		const { run, allowWith } = setup();
		allowWith([`Bash(${CLI_PATH}:*)`, ...HOOKS_ALLOW_RULES]);
		expect((await run("allow-rule")).status).toBe("warn");
	});
});
