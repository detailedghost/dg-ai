import { existsSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import { dirname, isAbsolute, join } from "node:path";
import { writeFileAtomic } from "@dg/common/node";
import { HOOKS } from "../manifest";
import type { SettingsWriter } from "../types";
import { readJsonObject, updateJsonFile } from "./json-file";
import { ownedCommand } from "./marker";

const PLUGIN_NAME = "dg-hooks";
const HEADER = "// generated by dg-skills hooks; do not edit";
const PLUGIN_MODE = 0o644;
const LIST_LINE = /^const HOOKS = (.*);$/m;

interface PluginHook {
	id: string;
	event: string;
	matcher: string;
	command: string;
	argv: string[];
}

const TEMPLATE = `
const TOOLS = { edit: "Edit", write: "Write", multiedit: "MultiEdit", bash: "Bash" };
const RENAMED = { filePath: "file_path", oldString: "old_string", newString: "new_string" };
const claudeShaped = (args) =>
  Object.fromEntries(Object.entries(args ?? {}).map(([k, v]) => [RENAMED[k] ?? k, v]));
const calls = new Map();
export default async ({ directory }) => {
  const { spawnSync } = await import("node:child_process");
  const run = (event) => async (input, output) => {
    const key = input.callID;
    if (event === "PreToolUse" && key) calls.set(key, output?.args);
    const args = output?.args ?? input.args ?? calls.get(key);
    if (event === "PostToolUse" && key) calls.delete(key);
    const tool = TOOLS[String(input.tool).toLowerCase()] ?? input.tool;
    for (const hook of HOOKS) {
      if (hook.event !== event || !new RegExp("^(?:" + hook.matcher + ")$").test(tool)) continue;
      const payload = JSON.stringify({ tool_name: tool, tool_input: claudeShaped(args), cwd: directory });
      const result = spawnSync(hook.argv[0], hook.argv.slice(1), { input: payload, encoding: "utf8", timeout: 10000 });
      if (result.status === 2) throw new Error(result.stderr);
    }
  };
  return { "tool.execute.before": run("PreToolUse"), "tool.execute.after": run("PostToolUse") };
};
`;

function render(hooks: PluginHook[]): string {
	return `${HEADER}\nconst HOOKS = ${JSON.stringify(hooks)};\n${TEMPLATE}`;
}

function readPluginIds(file: string): string[] {
	if (!existsSync(file)) return [];
	const text = readFileSync(file, "utf8");
	if (text.split("\n", 1)[0] !== HEADER)
		throw new Error(
			`${file} was not generated by dg-skills hooks; move it aside and run the command again`,
		);
	const match = LIST_LINE.exec(text);
	return match?.[1]
		? (JSON.parse(match[1]) as { id: string }[]).map((h) => h.id)
		: [];
}

function pluginList(doc: Record<string, unknown>): string[] {
	return Array.isArray(doc.plugin) ? (doc.plugin as string[]) : [];
}

export function opencodeWriter(
	home: string,
	launcher: string,
	configHome?: string,
): SettingsWriter {
	const base =
		configHome && isAbsolute(configHome) ? configHome : join(home, ".config");
	const dir = join(base, "opencode");
	const json = join(dir, "opencode.json");
	const file = join(dir, "plugins", "dg-hooks.js");

	async function dropLegacyEntry(): Promise<void> {
		if (!existsSync(json)) return;
		await updateJsonFile(json, (doc) => {
			const list = pluginList(doc);
			return list.includes(PLUGIN_NAME)
				? { ...doc, plugin: list.filter((p) => p !== PLUGIN_NAME) }
				: doc;
		});
	}

	function renderFor(ids: Set<string>): string {
		return render(
			HOOKS.filter((d) => ids.has(d.id)).map((d) => ({
				id: d.id,
				event: d.event,
				matcher: d.matcher ?? ".*",
				command: ownedCommand(launcher, d.id),
				argv: [launcher, "hooks", "run", d.id],
			})),
		);
	}

	return {
		dir,
		file,
		check() {
			if (existsSync(json)) readJsonObject(json);
			readPluginIds(file);
		},
		async enable(defs) {
			await dropLegacyEntry();
			const supported = defs.filter(
				(d) => d.event !== "SessionStart" && d.runtimes.includes("opencode"),
			);
			if (supported.length === 0) return [];
			const wanted = new Set([
				...readPluginIds(file),
				...supported.map((d) => d.id),
			]);
			mkdirSync(dirname(file), { recursive: true });
			writeFileAtomic(file, renderFor(wanted), PLUGIN_MODE);
			return supported.map((d) => d.id);
		},
		async disable(ids) {
			await dropLegacyEntry();
			const current = readPluginIds(file);
			const removed = current.filter((id) => !ids || ids.includes(id));
			if (removed.length === 0) return [];
			const kept = new Set(current.filter((id) => !removed.includes(id)));
			if (kept.size > 0) writeFileAtomic(file, renderFor(kept), PLUGIN_MODE);
			else rmSync(file, { force: true });
			return removed;
		},
		enabled: () => readPluginIds(file),
	};
}
