import { existsSync, mkdirSync, readFileSync, renameSync, rmSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { writeFileAtomic } from "@dg/common/node";
import type { CommandRunner } from "../types";

const MARKER = "# generated by dg-skills hooks; do not edit";
const HOOK_MODE = 0o755;

export interface CommitMsgHook {
	file: string;
	hooksPathSet: boolean;
}

const shellQuote = (text: string) => `'${text.replaceAll("'", `'\\''`)}'`;
const chained = (file: string) => `${file}.dg-orig`;

export function isOwnedScript(file: string): boolean {
	return existsSync(file) && readFileSync(file, "utf8").includes(MARKER);
}

export async function locateCommitMsgHook(
	cwd: string,
	run: CommandRunner,
): Promise<CommitMsgHook> {
	const common = await run(["git", "rev-parse", "--git-common-dir"], { cwd });
	if (common.status !== 0 || !common.stdout.trim())
		throw new Error(`${cwd} is not inside a git repository`);
	const hooksPath = await run(["git", "config", "--get", "core.hooksPath"], {
		cwd,
	});
	return {
		file: resolve(cwd, common.stdout.trim(), "hooks", "commit-msg"),
		hooksPathSet: hooksPath.status === 0,
	};
}

function script(file: string, launcher: string, id: string): string {
	return [
		"#!/bin/sh",
		MARKER,
		`${shellQuote(launcher)} hooks run ${id} "$1" || true`,
		`orig=${shellQuote(chained(file))}`,
		'[ -x "$orig" ] && exec "$orig" "$@"',
		"exit 0",
		"",
	].join("\n");
}

/** Writes the commit-msg hook; a hook dg did not write moves aside and runs after it. */
export function installCommitMsgHook(
	file: string,
	launcher: string,
	id: string,
): void {
	mkdirSync(dirname(file), { recursive: true });
	if (existsSync(file) && !isOwnedScript(file)) {
		if (existsSync(chained(file)))
			throw new Error(
				`${chained(file)} already exists; move it aside and run the command again`,
			);
		renameSync(file, chained(file));
	}
	writeFileAtomic(file, script(file, launcher, id), HOOK_MODE);
}

/** Removes the hook dg wrote and restores the chained one; returns false when dg wrote none. */
export function removeCommitMsgHook(file: string): boolean {
	if (!isOwnedScript(file)) return false;
	if (existsSync(chained(file))) renameSync(chained(file), file);
	else rmSync(file);
	return true;
}
