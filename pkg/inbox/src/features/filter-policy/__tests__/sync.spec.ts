describe("synthetic declared filters example", () => {
	test("matches the shipped example and stays clear of safety blocks", async () => {
		const example = buildDeclaredFiltersExample();
		expect(example.filters.length).toBeGreaterThanOrEqual(60);
		expect(example.filters.some((filter) => filter.sieve.includes("include"))).toBe(
			true,
		);
		expect(
			example.filters.some((filter) => filter.sieve.includes("email-organizer")),
		).toBe(true);
		expect(example.filters.some((filter) => filter.name === "+Family & .family")).toBe(
			true,
		);
		expect(example.folders.some((folder) => folder.path.includes("/"))).toBe(true);
		const parsed = parseDeclaredFilters(example);
		const plan = buildSyncPlan({
			desiredFilters: parsed.filters,
			desiredFolders: parsed.folders,
			liveFilters: parsed.observed?.filters ?? [],
			liveFolders: (parsed.observed?.folders ?? []).map((folder) => ({
				...folder,
			})),
			observedFilters: parsed.observed?.filters,
			observedFolders: parsed.observed?.folders,
			naming: parsed.policy.naming,
		});
		const issues = safetyIssues({
			actions: plan.actions,
			notices: plan.notices,
			policy: parsed.policy.safety,
			keepFirst: parsed.policy.keepFirst,
			liveFilters: parsed.observed?.filters ?? [],
		});
		expect(issues).toEqual([]);
		expect(plan.notices.some((notice) => notice.op === "rename-proposal")).toBe(
			true,
		);
		expect(plan.actions.some((action) => action.op === "delete-filter")).toBe(
			false,
		);
		expect(planHash(plan)).toHaveLength(64);
		const shipped = await Bun.file(
			new URL("../../../../examples/declared-filters.example.json", import.meta.url),
		).json();
		expect(shipped).toEqual(example);
	});
});

