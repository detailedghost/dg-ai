import { describe, expect, test } from "bun:test";
import { redactText } from "../../../privacy/redact";
import {
	fullSieveOrThrow,
	normalizeSieve,
	parseSieve,
	sieveLooksTruncated,
} from "../parse";

const extensionHeader = [
	'require ["include", "environment", "variables", "relational", "comparator-i;ascii-numeric", "spamtest"];',
	'if allof (environment :matches "vnd.proton.origination" "*", address :all :comparator "i;unicode-casemap" :is "From" "news@shop.example") {',
	'  fileinto "fin/banking";',
	"}",
].join("\n");

const organizerHeader = [
	'require ["fileinto", "imap4flags"];',
	"# Generated by email-organizer.",
	'if anyof (address :all :is "To" "owner+family@example.test", address :all :is "To" "owner.family@example.test") {',
	'  fileinto :create "family";',
	"}",
].join("\n");

describe("sieve parsing", () => {
	test("reads extension requires and email-organizer comments", () => {
		const extension = parseSieve(extensionHeader);
		expect(extension.style).toBe("extension-requires");
		expect(extension.requires).toContain("include");
		expect(extension.requires).toContain("environment");
		expect(extension.fileinto).toEqual(["fin/banking"]);
		expect(extension.domains).toEqual(["shop.example"]);
		expect(extension.truncated).toBe(false);
		const organizer = parseSieve(organizerHeader);
		expect(organizer.style).toBe("email-organizer");
		expect(organizer.comments).toEqual(["Generated by email-organizer."]);
		expect(organizer.fileinto).toEqual(["family"]);
		expect(organizer.plusTags).toEqual(["family"]);
		expect(organizer.dotTags).toEqual(["family"]);
		expect(parseSieve('require ["fileinto"];\nif true {\n  keep;\n}\n').style).toBe(
			"plain",
		);
	});

	test("reads local-part plus and dot tags", () => {
		const parsed = parseSieve(
			[
				'require ["fileinto"];',
				'if address :localpart :matches "To" "*+travel" {',
				'  fileinto "travel";',
				"}",
				'if address :localpart :is "To" "owner.bills" {',
				'  fileinto "bills";',
				"}",
			].join("\n"),
		);
		expect(parsed.plusTags).toEqual(["travel"]);
		expect(parsed.dotTags).toContain("bills");
	});

	test("flags redacted inventory snippets and refuses to store them", () => {
		const full = organizerHeader;
		const snippet = redactText(full, 80);
		expect(snippet.length).toBeLessThanOrEqual(80);
		expect(sieveLooksTruncated(snippet)).toBe(true);
		expect(sieveLooksTruncated("")).toBe(true);
		expect(sieveLooksTruncated('require ["fileinto"]; fileinto "fin')).toBe(true);
		expect(
			sieveLooksTruncated('require ["fileinto"];\nif true {\n  keep;\n'),
		).toBe(true);
		expect(() =>
			fullSieveOrThrow({
				conditions: [snippet],
				actions: ['fileinto "family";'],
			}),
		).toThrow(/truncated or redacted/);
		expect(fullSieveOrThrow({ conditions: ["keep"], actions: [full] })).toBe(full);
		expect(normalizeSieve(" a \r\n")).toBe("a");
	});
});
